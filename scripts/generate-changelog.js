#!/usr/bin/env node
/**
 * Generate CHANGELOG.md from the version control history.
 *
 * WHY THIS SCRIPT EXISTS
 * ----------------------
 * A changelog that is written by hand at release time is written from memory,
 * and is therefore incomplete in exactly the releases where it matters most -
 * the busy ones. The history already records every change, and the annotated
 * tags already record every release, so the document is derived from those two
 * facts rather than restated.
 *
 * Because it is generated, the changelog is a build artefact of the repository
 * and never a source of truth. It is regenerated by `make changelog` and
 * reviewed as part of the release branch, so the generated text is still
 * inspected before it is published.
 *
 * Usage:
 *   npm run changelog            # rewrite CHANGELOG.md
 *   npm run changelog -- --check # exit 1 if the file is out of date
 *   node scripts/generate-changelog.js --revision v1.0.0
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(projectRoot, 'CHANGELOG.md');

/** Conventional Commit type to section heading, in the order sections appear. */
const SECTIONS = [
  ['feat', 'Added'],
  ['fix', 'Fixed'],
  ['perf', 'Performance'],
  ['refactor', 'Changed'],
  ['build', 'Build'],
  ['ci', 'Continuous integration'],
  ['test', 'Tests'],
  ['docs', 'Documentation'],
  ['chore', 'Maintenance'],
  ['style', 'Style'],
  ['revert', 'Reverted'],
];

/** Types that describe the project's own plumbing and are hidden by default. */
const HIDDEN_TYPES = new Set(['chore', 'style']);

class GitUnavailableError extends Error {}

/** Run a git command and return its standard output. */
function git(args, { allowFailure = false } = {}) {
  try {
    return execFileSync('git', args, {
      cwd: projectRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 32 * 1024 * 1024,
    }).trim();
  } catch (error) {
    // A restrictive or supervised environment can refuse to allow a child
    // process at all. The remedy is the same as for a missing binary, so both
    // are reported as "git is unavailable" rather than as a crash.
    if (['ENOENT', 'EPERM', 'EACCES'].includes(String(error.code).toUpperCase())) {
      throw new GitUnavailableError(
        `The \`git\` executable could not be run in this environment (${error.code}).`,
      );
    }
    if (allowFailure) return '';
    throw new Error(`git ${args.join(' ')} failed: ${error.stderr?.toString().trim() || error.message}`);
  }
}

function gitAvailable() {
  try {
    git(['rev-parse', '--is-inside-work-tree']);
    return true;
  } catch {
    return false;
  }
}

/** Release tags, newest first by version rather than by date. */
function releaseTags() {
  const tags = git(['tag', '--list', 'v[0-9]*'], { allowFailure: true })
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

  return tags.sort(compareVersions).reverse();
}

/** Compare two v-prefixed semantic versions. */
export function compareVersions(left, right) {
  const parse = (value) => value.replace(/^v/, '').split(/[.\-+]/).map((part) => (/^\d+$/.test(part) ? Number(part) : part));
  const a = parse(left);
  const b = parse(right);

  for (let index = 0; index < Math.max(a.length, b.length); index += 1) {
    const x = a[index] ?? 0;
    const y = b[index] ?? 0;
    if (x === y) continue;
    if (typeof x === 'number' && typeof y === 'number') return x - y;
    return String(x).localeCompare(String(y));
  }
  return 0;
}

/** Read commits in the range `fromTag..toTag`, or all commits when none is given. */
function commitsInRange(fromTag, toTag) {
  const range = fromTag ? `${fromTag}..${toTag}` : toTag;

  // A unit separator between fields and a record separator between commits keeps
  // a multi-line body intact, which a single-line format cannot do.
  const format = '%H%x1f%h%x1f%s%x1f%b%x1f%an%x1e';
  const raw = git(['log', '--no-merges', `--format=${format}`, range], { allowFailure: true });
  if (!raw) return [];

  return raw
    .split('\x1e')
    .map((record) => record.trim())
    .filter(Boolean)
    .map((record) => {
      const [sha, shortSha, subject, body, author] = record.split('\x1f');
      return { sha, shortSha, subject: (subject ?? '').trim(), body: (body ?? '').trim(), author: (author ?? '').trim() };
    });
}

/** Parse a Conventional Commit subject into type, scope and description. */
export function parseSubject(subject) {
  const match = /^(?<type>[a-z]+)(?:\((?<scope>[^)]+)\))?(?<breaking>!)?:\s*(?<description>.+)$/.exec(subject);
  if (!match) return { type: 'other', scope: null, breaking: false, description: subject };
  return {
    type: match.groups.type,
    scope: match.groups.scope ?? null,
    breaking: Boolean(match.groups.breaking),
    description: match.groups.description.trim(),
  };
}

/** The release date recorded on the tag itself, not the date the script ran. */
function tagDate(tag) {
  const iso = git(['log', '-1', '--format=%cI', tag], { allowFailure: true });
  return iso ? iso.slice(0, 10) : new Date().toISOString().slice(0, 10);
}

/**
 * Build the markdown document.
 */
export function buildChangelog({ includeMaintenance = false, repositoryUrl = null } = {}) {
  const tags = releaseTags();
  const sections = [];

  sections.push('# Changelog');
  sections.push('');
  sections.push(
    'All notable changes to this project are documented in this file.\n\n' +
      'The format follows [Keep a Changelog](https://keepachangelog.com/en/1.1.0/) and this\n' +
      'project adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html).',
  );
  sections.push('');
  sections.push(
    '> This file is **generated from the Git history** by `scripts/generate-changelog.js`.\n' +
      '> Edit the history, not this file: run `make changelog` to regenerate it.',
  );
  sections.push('');

  if (tags.length === 0) {
    sections.push('## [Unreleased]');
    sections.push('');
    sections.push('No release tag exists yet. Commit history so far:');
    sections.push('');
    sections.push(renderEntries(commitsInRange(null, 'HEAD'), { includeMaintenance, repositoryUrl }));
    sections.push('');
    return `${sections.join('\n').trimEnd()}\n`;
  }

  // Unreleased work: everything on HEAD that is not reachable from the newest tag.
  const unreleased = commitsInRange(tags[0], 'HEAD');
  if (unreleased.length > 0) {
    sections.push('## [Unreleased]');
    sections.push('');
    sections.push(renderEntries(unreleased, { includeMaintenance, repositoryUrl }));
    sections.push('');
  }

  for (let index = 0; index < tags.length; index += 1) {
    const tag = tags[index];
    const previousTag = tags[index + 1] ?? null;
    const commits = commitsInRange(previousTag, tag);

    sections.push(`## [${tag.replace(/^v/, '')}] - ${tagDate(tag)}`);
    sections.push('');

    if (commits.length === 0) {
      sections.push('_No changes were recorded between this release and the previous one._');
      sections.push('');
    } else {
      sections.push(renderEntries(commits, { includeMaintenance, repositoryUrl }));
      sections.push('');
    }

    if (previousTag && repositoryUrl) {
      sections.push(`**Full comparison:** [\`${previousTag}...${tag}\`](${repositoryUrl}/compare/${previousTag}...${tag})`);
      sections.push('');
    }
  }

  const latest = tags[0].replace(/^v/, '');
  if (repositoryUrl) {
    sections.push(`[Unreleased]: ${repositoryUrl}/compare/${tags[0]}...HEAD`);
    for (let index = 0; index < tags.length; index += 1) {
      const tag = tags[index];
      const previousTag = tags[index + 1];
      const version = tag.replace(/^v/, '');
      sections.push(
        previousTag
          ? `[${version}]: ${repositoryUrl}/compare/${previousTag}...${tag}`
          : `[${version}]: ${repositoryUrl}/releases/tag/${tag}`,
      );
    }
  } else {
    sections.push(`Current release: **${latest}**`);
  }
  sections.push('');

  return `${sections.join('\n').trimEnd()}\n`;
}

/** Group commits by Conventional Commit type and render each section. */
function renderEntries(commits, { includeMaintenance, repositoryUrl }) {
  const groups = new Map();
  const breaking = [];

  for (const commit of commits) {
    const parsed = parseSubject(commit.subject);
    if (parsed.breaking || /^BREAKING CHANGE:/m.test(commit.body)) breaking.push(commit);
    if (!includeMaintenance && HIDDEN_TYPES.has(parsed.type)) continue;

    const heading = SECTIONS.find(([type]) => type === parsed.type)?.[1] ?? 'Other';
    if (!groups.has(heading)) groups.set(heading, []);
    groups.get(heading).push({ commit, parsed });
  }

  const order = SECTIONS.map(([, heading]) => heading);
  const lines = [];

  if (breaking.length > 0) {
    lines.push('### Breaking changes');
    lines.push('');
    for (const commit of breaking) {
      lines.push(`- ${linkCommit(commit, repositoryUrl)}`);
    }
    lines.push('');
  }

  const headings = [...groups.keys()].sort((a, b) => {
    const ai = order.indexOf(a);
    const bi = order.indexOf(b);
    return (ai === -1 ? order.length : ai) - (bi === -1 ? order.length : bi);
  });

  for (const heading of headings) {
    lines.push(`### ${heading}`);
    lines.push('');
    for (const { commit, parsed } of groups.get(heading)) {
      const scope = parsed.scope ? `**${parsed.scope}:** ` : '';
      lines.push(`- ${scope}${parsed.description} (${linkCommit(commit, repositoryUrl)})`);
    }
    lines.push('');
  }

  if (lines.length === 0) {
    lines.push('_No entries._');
    lines.push('');
  }

  return lines.join('\n').trimEnd();
}

function linkCommit(commit, repositoryUrl) {
  return repositoryUrl ? `[\`${commit.shortSha}\`](${repositoryUrl}/commit/${commit.sha})` : `\`${commit.shortSha}\``;
}

/* -------------------------------------------------------------------------- */

if (import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/')}` || process.argv[1]?.endsWith('generate-changelog.js')) {
  if (process.argv.includes('--help') || process.argv.includes('-h')) {
    process.stdout.write(
      [
        '',
        'Generate CHANGELOG.md from the Git history.',
        '',
        'Usage: node scripts/generate-changelog.js [options]',
        '',
        'Options:',
        '  --check               Exit 1 if CHANGELOG.md differs from the generated text',
        '  --include-maintenance Include chore and style commits (hidden by default)',
        '  --repository <url>    Base URL used to link commits and comparisons',
        '  --stdout              Print to standard output instead of writing the file',
        '  --help, -h            Show this message',
        '',
      ].join('\n'),
    );
    process.exit(0);
  }

  if (!gitAvailable()) {
    process.stderr.write(
      '\n  Git is not available in this environment.\n' +
        '  CHANGELOG.md was not regenerated; the committed copy remains authoritative.\n\n',
    );
    // Exit 0 deliberately: a missing git binary must not fail a pipeline stage
    // that only wanted to refresh a document.
    process.exit(0);
  }

  const repositoryIndex = process.argv.indexOf('--repository');
  const repositoryUrl = repositoryIndex === -1 ? null : process.argv[repositoryIndex + 1]?.replace(/\/$/, '') ?? null;

  let generated;
  try {
    generated = buildChangelog({
      includeMaintenance: process.argv.includes('--include-maintenance'),
      repositoryUrl,
    });
  } catch (error) {
    if (error instanceof GitUnavailableError) {
      process.stderr.write(`\n  ${error.message}\n  CHANGELOG.md was not regenerated.\n\n`);
      process.exit(0);
    }
    throw error;
  }

  if (process.argv.includes('--stdout')) {
    process.stdout.write(generated);
    process.exit(0);
  }

  if (process.argv.includes('--check')) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
    if (current === generated) {
      process.stdout.write('\n  CHANGELOG.md is up to date.\n\n');
      process.exit(0);
    }
    process.stderr.write('\n  CHANGELOG.md is out of date. Run `make changelog` and commit the result.\n\n');
    process.exit(1);
  }

  writeFileSync(outputPath, generated, 'utf8');

  const releases = releaseTags().length;
  const commits = commitsInRange(null, 'HEAD').length;
  process.stdout.write(
    `\n  CHANGELOG.md written\n${'  ' + '-'.repeat(60)}\n` +
      `  release tags              ${releases}\n` +
      `  commits considered        ${commits}\n` +
      `  output                    ${outputPath}\n\n`,
  );
  process.exit(0);
}
